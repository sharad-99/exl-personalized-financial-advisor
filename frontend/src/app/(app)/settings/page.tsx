"use client";

import { LogOut } from "lucide-react";
import { useState } from "react";

import { DataQualityPanel } from "@/components/dashboard/data-quality-panel";
import { Button, Card, ErrorState, LoadingState, Notice, PageHeader } from "@/components/shared/ui";
import { useApi } from "@/hooks/use-api";
import { useSession } from "@/hooks/use-session";
import { ApiError, apiSend } from "@/lib/api-client";
import { signOut } from "@/lib/auth";
import { formatDate } from "@/lib/formatting";
import type { Analytics, Me } from "@/types/api";

export default function SettingsPage() {
  const { me, customerId, refreshMe } = useSession();
  const analytics = useApi<Analytics>(customerId ? `customers/${customerId}/analytics` : null);
  const [busy, setBusy] = useState(false);
  const [message, setMessage] = useState<string | null>(null);
  const [error, setError] = useState<string | null>(null);
  if (!me) return null;
  const isCustomer = me.role === "customer";

  async function update(field: "data_sharing_consent" | "marketing_consent", value: boolean) {
    setBusy(true);
    setError(null);
    try {
      await apiSend<Me>("PATCH", "me/consent", { [field]: value });
      setMessage(field === "data_sharing_consent" && !value ? "Personalised insights are paused. Re-check your data in the money coach to clear open recommendations." : "Preferences saved.");
      refreshMe();
    } catch (err) {
      setError(err instanceof ApiError ? err.message : "Could not save your preferences.");
    } finally {
      setBusy(false);
    }
  }

  return (
    <div className="space-y-6">
      <PageHeader title="Settings & data transparency" />
      <Notice>
        <p className="font-medium text-ink">This is a simulated environment</p>
        Every customer, account, transaction and balance shown here was generated by a reproducible synthetic data generator. No real bank or personal data is used, and nothing here is regulated investment advice.
      </Notice>

      <div className="grid gap-6 lg:grid-cols-2">
        <Card title="Data freshness">
          {analytics.loading && <LoadingState />}
          {analytics.error && <ErrorState error={analytics.error} onRetry={analytics.reload} />}
          {analytics.data && (
            <div className="space-y-3 text-sm">
              <DataQualityPanel dq={analytics.data.data_quality} compact />
              <ul className="list-disc space-y-1 pl-5 text-ink-2">
                {analytics.data.data_quality.confidence_reasons.map((r) => <li key={r}>{r}</li>)}
              </ul>
              <p className="text-xs text-ink-3">Balance status: {analytics.data.data_quality.balance_status}. Analytics evaluated as of {formatDate(analytics.data.period.as_of)}.</p>
            </div>
          )}
        </Card>

        <Card title="Privacy and consent">
          {isCustomer ? (
            <div className="space-y-4 text-sm">
              <label className="flex items-start gap-3">
                <input type="checkbox" className="mt-1 size-4 accent-teal" checked={me.data_sharing_consent} disabled={busy} onChange={(e) => void update("data_sharing_consent", e.target.checked)} />
                <span>
                  <span className="font-medium">Use my data for personalised insights</span>
                  <span className="block text-ink-2">When off, no new recommendations are generated. Your own analytics remain visible to you.</span>
                </span>
              </label>
              <label className="flex items-start gap-3">
                <input type="checkbox" className="mt-1 size-4 accent-teal" checked={me.marketing_consent} disabled={busy} onChange={(e) => void update("marketing_consent", e.target.checked)} />
                <span>
                  <span className="font-medium">Product updates</span>
                  <span className="block text-ink-2">Recorded for completeness; this demo never sends messages.</span>
                </span>
              </label>
              <p className="text-xs text-ink-3">Last updated {formatDate(me.consent_updated_at)}.</p>
              {message && <p role="status" className="text-good">{message}</p>}
              {error && <p role="alert" className="text-bad">{error}</p>}
            </div>
          ) : (
            <p className="text-sm text-ink-2">Consent is managed by each customer. Advisors have read-only access.</p>
          )}
        </Card>

        <Card title="How your data is used">
          <ul className="list-disc space-y-1 pl-5 text-sm text-ink-2">
            <li>Stored: profile, accounts, transactions, goals, obligations, recommendations and your feedback.</li>
            <li>Computed on request (never stored): totals, averages, savings rate, emergency-fund coverage and trends.</li>
            <li>Every recommendation keeps the inputs and rule version used, so it can be explained later.</li>
            <li>Activity such as feedback and consent changes is written to an append-only audit log.</li>
          </ul>
        </Card>

        <Card title="Session">
          <p className="mb-3 text-sm text-ink-2">Signed in as <span className="font-medium text-ink">{me.email}</span>. Signing out clears your session cookie on this device.</p>
          <Button variant="secondary" onClick={() => void signOut()}><LogOut className="size-4" aria-hidden /> Sign out</Button>
        </Card>
      </div>
    </div>
  );
}
