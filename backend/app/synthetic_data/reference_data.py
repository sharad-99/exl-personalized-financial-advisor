def _sql_literal(value: str) -> str:
    return "'" + value.replace("'", "''") + "'"


def render_reference_sql() -> str:
    lines = [
        "-- =============================================================================",
        "-- Reference data: recommendation rule catalogue (v1) and generic product types.",
        "-- GENERATED by backend/app/synthetic_data/reference_data.py -- do not edit by hand.",
        "-- Regenerate: cd backend && python -m app.synthetic_data.reference_data > \\",
        "--   ../supabase/migrations/20261024000300_reference_data.sql",
        "-- =============================================================================",
        "",
        "insert into public.recommendation_rules (rule_id, version, category, name, description, parameters)",
        "values",
    ]
    rule_rows = [
        f"  ({_sql_literal(r.rule_id)}, {r.version}, {_sql_literal(r.category)}, {_sql_literal(r.name)}, "
        f"{_sql_literal(r.description)}, {_sql_literal(json.dumps(r.parameters, sort_keys=True))}::jsonb)"
        for r in RULES.values()
    ]
    lines.append(",\n".join(rule_rows))
    lines.append("on conflict (rule_id, version) do nothing;")
    lines += ["", "insert into public.financial_products (code, name, product_type, description)", "values"]
    product_rows = [
        f"  ({_sql_literal(p['code'])}, {_sql_literal(p['name'])}, {_sql_literal(p['product_type'])}, "
        f"{_sql_literal(p['description'])})"
        for p in FINANCIAL_PRODUCTS
    ]
    lines.append(",\n".join(product_rows))
    lines.append("on conflict (code) do update set name = excluded.name, description = excluded.description;")
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    print(render_reference_sql(), end="")
